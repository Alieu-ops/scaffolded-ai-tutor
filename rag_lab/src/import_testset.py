r"""
Import a large generated test set (Markdown with one ```yaml block), check it, and split it
ONCE into a development part (for tuning) and a held-out part (frozen, for confirmation).

Run from the app folder:
    .\.venv\Scripts\python.exe rag_lab\src\import_testset.py "C:\Users\Hp\Downloads\rag_retrieval_testset_430.md"

Writes:
    rag_lab/testset/v2_dev.yaml       about 60% of each question type
    rag_lab/testset/v2_heldout.yaml   about 40% of each question type (do not tune on it)

Checks (the run stops if a check fails):
    - every expected section_id exists in section_map.md and its pages match the map exactly
    - no duplicate ids or duplicate question texts
Exclusions: questions found to be mislabelled during review are listed in EXCLUDE with the reason.

The split is random but REPRODUCIBLE: a fixed seed means running this again gives the same
split. It is stratified: each type (direct, paraphrase, ...) is split 60/40 separately, so
both parts contain the same mix.
"""

from __future__ import annotations

import random
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

from common import LAB, use_utf8_output

TESTSET_DIR = LAB / "testset"
SEED = 20261013
DEV_SHARE = 0.6

# Checked 13 Oct 2026 against the extracted text (with an AI assistant).
EXCLUDE = {
    "n040": "labelled absent, but Godwin p. 19 (3.1.2 Experimental data) explains random assignment "
            "to treatment and control groups, so the topic is covered",
}


def read_questions(markdown_file: Path) -> list[dict]:
    blocks = re.findall(r"```yaml\n(.*?)```", markdown_file.read_text(encoding="utf-8"), re.S)
    if len(blocks) != 1:
        raise SystemExit(f"Expected exactly one ```yaml block, found {len(blocks)}.")
    return yaml.safe_load(blocks[0])


def read_section_map() -> dict[str, tuple[int, int]]:
    sections = {}
    for line in (TESTSET_DIR / "section_map.md").read_text(encoding="utf-8").splitlines():
        match = re.match(r"\| ([OG]-[\d.]+) \| .*? \| (\d+)-(\d+) \|", line)
        if match:
            sections[match.group(1)] = (int(match.group(2)), int(match.group(3)))
    return sections


def check(questions: list[dict], sections: dict) -> None:
    problems = []
    ids = Counter(q["id"] for q in questions)
    texts = Counter(re.sub(r"\W+", " ", q["question"].lower()).strip() for q in questions)
    problems += [f"duplicate id {i}" for i, n in ids.items() if n > 1]
    problems += [f"duplicate question '{t}'" for t, n in texts.items() if n > 1]
    for q in questions:
        for e in q.get("expected") or []:
            pages = sections.get(e.get("section_id"))
            if pages is None:
                problems.append(f"{q['id']}: unknown section {e.get('section_id')}")
            elif tuple(e["pages"]) != pages:
                problems.append(f"{q['id']}: pages {e['pages']} differ from section map {list(pages)}")
    if problems:
        raise SystemExit("Problems found:\n  " + "\n  ".join(problems))


def split(questions: list[dict]) -> tuple[list[dict], list[dict]]:
    by_type: dict[str, list[dict]] = defaultdict(list)
    for q in questions:
        by_type[q["type"]].append(q)
    rng = random.Random(SEED)
    dev, heldout = [], []
    for kind in sorted(by_type):
        group = sorted(by_type[kind], key=lambda q: q["id"])
        rng.shuffle(group)
        cut = round(len(group) * DEV_SHARE)
        dev += group[:cut]
        heldout += group[cut:]
    order = lambda q: q["id"]
    return sorted(dev, key=order), sorted(heldout, key=order)


def write(path: Path, part: str, questions: list[dict], source: str) -> None:
    header = (f"# RAG lab test set v2 ({part}). Generated by import_testset.py from {source}.\n"
              f"# Questions drafted with ChatGPT from the section map; labels checked against the map;\n"
              f"# absent questions spot-checked against the extracted text. Split seed {SEED}.\n"
              + ("# HELD-OUT: use only to confirm results; never tune settings on it; do not edit it.\n"
                 if part == "held-out" else "# DEVELOPMENT: may be used to compare and tune settings.\n"))
    body = {"version": "2.0", "status": "imported", "books_indexed": ["olivier", "godwin"], "questions": questions}
    path.write_text(header + "\n" + yaml.safe_dump(body, sort_keys=False, allow_unicode=True, width=120),
                    encoding="utf-8")


def main(argv: list[str]) -> None:
    use_utf8_output()
    if not argv:
        raise SystemExit('Usage: import_testset.py "path\\to\\testset.md"')
    source = Path(argv[0])
    questions = read_questions(source)
    sections = read_section_map()
    check(questions, sections)
    kept = [q for q in questions if q["id"] not in EXCLUDE]
    for qid, reason in EXCLUDE.items():
        print(f"excluded {qid}: {reason}")
    dev, heldout = split(kept)
    write(TESTSET_DIR / "v2_dev.yaml", "development", dev, source.name)
    write(TESTSET_DIR / "v2_heldout.yaml", "held-out", heldout, source.name)
    print(f"\n{len(questions)} read, {len(kept)} kept -> development {len(dev)}, held-out {len(heldout)}")
    for kind in sorted({q["type"] for q in kept}):
        print(f"  {kind:<15} dev {sum(q['type'] == kind for q in dev):>3}   held-out {sum(q['type'] == kind for q in heldout):>3}")
    print(f"Saved {TESTSET_DIR / 'v2_dev.yaml'}\n      {TESTSET_DIR / 'v2_heldout.yaml'}")


if __name__ == "__main__":
    main(sys.argv[1:])
